  function josa(word, withB, noB) {
    const c = word.charCodeAt(word.length - 1);
    if (c < 0xAC00 || c > 0xD7A3) return noB;
    return ((c - 0xAC00) % 28) ? withB : noB;
  }

  function ageLine(a) {
    const now = new Date();
    const b = new Date(a.solar.y, a.solar.m - 1, a.solar.d);
    let months = (now.getFullYear() - b.getFullYear()) * 12 + (now.getMonth() - b.getMonth());
    if (now.getDate() < b.getDate()) months -= 1;
    if (months < 0) return '아직 태어나기 전이에요. 예정일로 본 사주예요.';
    if (months < 24) return `지금 ${months}개월쯤이에요.`;
    return `지금 ${Math.floor(months / 12)}살쯤이에요.`;
  }

